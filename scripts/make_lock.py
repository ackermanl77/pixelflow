"""Write requirements-lock.txt: the exact versions of every package (and
transitive dependency) of requirements.txt + requirements-desktop.txt that
are installed in the interpreter running this script (report item K4).

    .venv\\Scripts\\python.exe scripts\\make_lock.py

The release build installs with `-c requirements-lock.txt`, so a rebuild
gets the same versions that were tested. torch is pinned without its local
"+cu130" tag (the CUDA flavour comes from the --index-url the build script
uses, see docs/BUILD.md). Packages listed in the requirements files but not
installed here are reported and left unpinned.
"""

import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["requirements.txt", "requirements-desktop.txt"]


def top_level() -> list:
    reqs = []
    for name in SOURCES:
        for line in (ROOT / name).read_text(encoding="utf-8").splitlines():
            line = line.split("#", 1)[0].strip()
            if line and not line.startswith("-"):
                reqs.append(Requirement(line))
    return reqs


def main() -> int:
    env = default_environment()
    pinned = {}
    missing = []
    stack = [(req, ()) for req in top_level()]
    while stack:
        req, extras = stack.pop()
        if req.marker is not None and not any(
            req.marker.evaluate({**env, "extra": extra}) for extra in (extras or ("",))
        ):
            continue
        key = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            missing.append(req.name)
            continue
        wanted_extras = tuple(sorted(req.extras))
        seen_key = (key, wanted_extras)
        if seen_key in pinned:
            continue
        pinned[seen_key] = (dist.metadata["Name"], dist.version)
        for raw in dist.requires or []:
            stack.append((Requirement(raw), wanted_extras))

    lines = {}
    for (key, _extras), (name, version) in pinned.items():
        lines[key] = f"{name}=={re.sub(r'[+].*$', '', version)}"
    header = [
        "# Generated by scripts/make_lock.py from the build venv - do not edit by hand.",
        f"# Python {sys.version.split()[0]} on {sys.platform}. Used as a constraints file:",
        "#   pip install -r requirements.txt -c requirements-lock.txt",
    ]
    if missing:
        header.append("# Not installed when generated (left unpinned): " + ", ".join(sorted(set(missing))))
    out = "\n".join(header + sorted(lines.values(), key=str.lower)) + "\n"
    (ROOT / "requirements-lock.txt").write_text(out, encoding="utf-8")
    print(f"wrote {len(lines)} pins to requirements-lock.txt")
    if missing:
        print("not installed:", ", ".join(sorted(set(missing))))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
