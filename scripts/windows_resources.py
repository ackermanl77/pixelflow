def app_version(version_file: str = VERSION_FILE) -> str:
    """The version build_release.ps1 stamped into backend/_version.py, or "dev" (read without importing)."""
    try:
        with open(version_file, encoding="utf-8") as handle:
            match = re.search(r'^__version__\s*=\s*"([^"]+)"', handle.read(), re.MULTILINE)
    except OSError:
        return "dev"
    return match.group(1) if match else "dev"


def version_tuple(version: str) -> tuple:
    """``"0.3.1"`` -> ``(0, 3, 1, 0)``; "dev" -> ``(0, 0, 0, 0)``; each number capped at 16 bits."""
    parts = [min(int(part), 0xFFFF) for part in re.findall(r"\d+", version)[:4]]
    return tuple(parts + [0] * (4 - len(parts)))


def version_file_text(version: str) -> str:
    numbers = version_tuple(version)
    shown = version if version_tuple(version) != (0, 0, 0, 0) else "0.0.0 (dev)"
    return _VERSION_TEMPLATE.format(numbers=repr(numbers), version=shown, publisher=PUBLISHER, product=PRODUCT)


def write_version_file(out_dir: str, version: str = None) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "pixelflow_version.txt")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(version_file_text(version or app_version()))
    return path


def write_manifest(out_dir: str) -> str:
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "PixelFlow.manifest")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(MANIFEST_XML)
    return path
